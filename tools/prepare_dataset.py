#!/usr/bin/env python3
"""
Prepare the D-Fire dataset (or any YOLO-format fire/smoke dataset) for training.

D-Fire ships as images/ + labels/ folders, sometimes already split into
train/ and test/. This script finds every (image, label) pair wherever it
lives, then rebuilds a clean train/val/test structure that Ultralytics expects:

    <output>/
      images/{train,val,test}/
      labels/{train,val,test}/
      dfire.yaml

It also prints a class-distribution report so you can verify the label
mapping before you waste an hour training with fire and smoke swapped.

Usage:
    python prepare_dataset.py --src ~/datasets/D-Fire --dst ./data/dfire
    python prepare_dataset.py --src ~/datasets/D-Fire --dst ./data/dfire --copy
"""

from __future__ import annotations

import argparse
import random
import shutil
from collections import Counter
from pathlib import Path

IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}

# D-Fire's label convention. Verify against the report this script prints:
# smoke instances should heavily outnumber fire instances in D-Fire.
CLASS_NAMES = ["smoke", "fire"]

SPLITS = ("train", "val", "test")


def find_pairs(src: Path) -> list[tuple[Path, Path]]:
    """Find every image that has a matching .txt label anywhere under src."""
    labels: dict[str, Path] = {}
    for txt in src.rglob("*.txt"):
        # Skip stray files like classes.txt / README notes
        if txt.name.lower() in {"classes.txt", "readme.txt", "notes.txt"}:
            continue
        labels.setdefault(txt.stem, txt)

    pairs: list[tuple[Path, Path]] = []
    missing = 0
    for img in src.rglob("*"):
        if img.suffix.lower() not in IMAGE_EXTS or not img.is_file():
            continue
        label = labels.get(img.stem)
        if label is None:
            missing += 1
            continue
        pairs.append((img, label))

    if missing:
        print(f"  note: {missing} image(s) had no matching label file, skipped")
    return pairs


def report_classes(pairs: list[tuple[Path, Path]]) -> None:
    """Count instances per class and how many images are pure background."""
    counts: Counter[int] = Counter()
    background = 0
    for _, label in pairs:
        lines = [ln for ln in label.read_text().splitlines() if ln.strip()]
        if not lines:
            background += 1
            continue
        for ln in lines:
            try:
                counts[int(ln.split()[0])] += 1
            except (ValueError, IndexError):
                print(f"  warning: malformed line in {label.name}: {ln[:60]!r}")

    print("\n  Class distribution")
    print("  " + "-" * 40)
    for cls_id in sorted(counts):
        name = CLASS_NAMES[cls_id] if cls_id < len(CLASS_NAMES) else f"id {cls_id}"
        print(f"    {cls_id}  {name:<8} {counts[cls_id]:>7,} instances")
    total = len(pairs)
    pct = 100 * background / total if total else 0
    print(f"\n    background (no objects): {background:,} images ({pct:.1f}%)")
    print("  " + "-" * 40)
    if background == 0:
        print("  WARNING: no negative images found. Your false-alarm rate will suffer.")


def place(pairs, dst: Path, split: str, copy: bool) -> None:
    img_dir = dst / "images" / split
    lbl_dir = dst / "labels" / split
    img_dir.mkdir(parents=True, exist_ok=True)
    lbl_dir.mkdir(parents=True, exist_ok=True)

    op = shutil.copy2 if copy else _symlink
    for img, label in pairs:
        op(img, img_dir / img.name)
        op(label, lbl_dir / f"{img.stem}.txt")


def _symlink(src: Path, dst: Path) -> None:
    if dst.is_symlink() or dst.exists():
        dst.unlink()
    dst.symlink_to(src.resolve())


def write_yaml(dst: Path) -> Path:
    yaml_path = dst / "dfire.yaml"
    yaml_path.write_text(
        f"""# Auto-generated by prepare_dataset.py
path: {dst.resolve()}
train: images/train
val: images/val
test: images/test

names:
"""
        + "".join(f"  {i}: {n}\n" for i, n in enumerate(CLASS_NAMES))
    )
    return yaml_path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--src", required=True, type=Path, help="Extracted D-Fire root")
    ap.add_argument("--dst", default=Path("./data/dfire"), type=Path)
    ap.add_argument("--val-frac", type=float, default=0.15)
    ap.add_argument("--test-frac", type=float, default=0.10)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument(
        "--copy",
        action="store_true",
        help="Copy files instead of symlinking (use on Windows or across filesystems)",
    )
    args = ap.parse_args()

    if not args.src.is_dir():
        raise SystemExit(f"Source directory not found: {args.src}")

    print(f"Scanning {args.src} ...")
    pairs = find_pairs(args.src)
    if not pairs:
        raise SystemExit("No image/label pairs found. Check the --src path.")
    print(f"  found {len(pairs):,} image/label pairs")

    report_classes(pairs)

    random.Random(args.seed).shuffle(pairs)
    n = len(pairs)
    n_test = int(n * args.test_frac)
    n_val = int(n * args.val_frac)
    splits = {
        "test": pairs[:n_test],
        "val": pairs[n_test : n_test + n_val],
        "train": pairs[n_test + n_val :],
    }

    if args.dst.exists():
        shutil.rmtree(args.dst)

    print(f"\nWriting to {args.dst} ({'copying' if args.copy else 'symlinking'}) ...")
    for split in SPLITS:
        place(splits[split], args.dst, split, args.copy)
        print(f"  {split:<6} {len(splits[split]):>7,} images")

    yaml_path = write_yaml(args.dst)
    print(f"\nDone. Data config: {yaml_path}")
    print(f"Next: python train.py --data {yaml_path}")


if __name__ == "__main__":
    main()
